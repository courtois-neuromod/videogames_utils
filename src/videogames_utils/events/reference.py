"""Build the common event reference of several datasets, ``docs/EVENT_REFERENCE.md``.

Each dataset documents its own game (``Game.reference``, from its ``code/game_specific/``);
this module puts those side by side, after the parts every dataset shares, with an
overview of which event each dataset produces and how often.

    python -m videogames_utils.events.reference /path/to/mario /path/to/mariostars \\
        /path/to/mario3 /path/to/shinobi -o docs/EVENT_REFERENCE.md

Datasets whose references are identical (e.g. two ports of one game sharing their
documentation) are rendered once, under a heading naming all of them.
"""

from __future__ import annotations

import argparse
import collections
import sys
from typing import Dict, List, Sequence

from . import tracking, vocabulary
from .emit import RAW_REPETITION, REPETITION
from .docs import rows_for
from .game import Game, load_game
from .run import census


def _summary_table(games: Sequence[Game], counts: Dict[str, collections.Counter]) -> str:
    lines = ["| Dataset | Game | Frame rate | Event rows | Distinct `trial_type` | "
             "Repetitions |", "|---|---|---|---|---|---|"]
    for game in games:
        c = counts[game.task]
        lines.append(f"| `{game.task}` | {game.name} | {game.frame_rate:.6f} Hz | "
                     f"{sum(c.values()):,} | {len(c)} | {c.get(REPETITION, 0):,} |")
    return "\n".join(lines)


def _event_matrix(games: Sequence[Game], counts: Dict[str, collections.Counter]) -> str:
    """Rows per event and dataset; a dash where the game has no such event."""
    entries: Dict[str, Dict[str, vocabulary.EventType]] = collections.defaultdict(dict)
    for game in games:
        for entry in game.vocabulary:
            entries[vocabulary.wildcard_name(entry.name)][game.task] = entry
    header = "| Event | " + " | ".join(f"`{g.task}`" for g in games) + " |"
    lines = [header, "|---|" + "---|" * len(games)]
    for key in sorted(entries):
        cells = []
        for game in games:
            entry = entries[key].get(game.task)
            cells.append("—" if entry is None else f"{rows_for(entry, counts[game.task]):,}")
        lines.append(f"| `{key}` | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _game_sections(games: Sequence[Game]) -> str:
    groups: Dict[str, List[Game]] = {}
    for game in games:
        groups.setdefault(game.reference.strip(), []).append(game)
    sections = []
    for text, group in groups.items():
        title = "; ".join(f"{g.name} — `{g.task}`" for g in group)
        sections.append(f"## {title}\n\n{text or '*No reference provided.*'}\n")
    return "\n---\n\n".join(sections)


def render(games: Sequence[Game], counts: Dict[str, collections.Counter]) -> str:
    return f"""# Event annotation reference — CNeuroMod videogame datasets

Every event type emitted into `sub-*/ses-*/func/*_desc-annotated_events.tsv`, what it
means, and how it is read from the game's RAM.

Generated by `python -m videogames_utils.events.reference` from each dataset's
`code/game_specific/` and annotated files; do not edit by hand. The machine-readable
version of each vocabulary is the dataset's `task-<task>_events.json`, and each dataset's
`code/annotations/README.md` carries its own part of this document with the row count of
every event.

{_summary_table(games, counts)}

---

## How to read this document

Event names are hierarchical: the part before the first `/` is the family, the parts
after it are qualifiers. A `*` stands for a qualifier filled in at generation time with a
decoded object name, e.g. `EnemyOnScreen/*` for `EnemyOnScreen/Goomba`.

Every segment is UpperCamelCase (`PlayerState/HitRecovery`).

### Columns

| Column | Meaning |
|---|---|
| `trial_type` | The event, from the game's controlled vocabulary. |
| `onset` | Seconds from the start of the fMRI run. |
| `duration` | Seconds; 0 for point events. |
| `frame_start`, `frame_stop` | Emulator frames, relative to the repetition. |
| `button` | Raw controller button behind an `Action/*` event; `n/a` otherwise. |
| `stim_file` | Path to the `.bk2`. **Set on the `Repetition` row only** — every other event sits inside exactly one of those windows. A repetition whose `.bk2` was lost keeps its row, with `stim_file` = `Missing file`, the onset (and, where the task logged it, the duration) from the plain `_events.tsv`, `n/a` frames and no events inside it. |

Per-repetition metadata — `phase`, `IndexInRun`, `IndexGlobal`, `IndexLevel` and
`Outcome` — is **not** repeated on event rows. It lives in the repetition's
`gamelogs/*_summary.json`, keyed by the `stim_file` on the container row.

Onsets are computed at the rate at which each game was displayed during acquisition
(see the table above): the emulator's native rate, or the screen's 60 Hz where the task
paced the game on the display.

### The container row

`Repetition` is one repetition of gameplay — one `.bk2` file. It is taken from the
`{RAW_REPETITION}` row of the run's plain `_events.tsv` and is the only row that carries
`stim_file`; every other event
falls inside its window. `duration` is the replay's frame count divided by the true frame
rate. It sorts first among rows sharing its onset, so slicing between container rows
assigns every event to the right repetition.

### Screens: what the game shows

The `Screen/*` rows say what the game is showing, as opposed to what the player is doing.
They **partition every repetition**: the rows of a repetition are contiguous, do not
overlap, and run from its first frame to its last, so exactly one is active at any frame
and `Screen/Gameplay` is the complement of the rest. All are durational.

The `PlayerState` **form rows** tile the frames on which the player is *alive in the
level*: every frame not inside a `Screen/Death`, `Screen/LevelIntro`, `Screen/GameOver` or
`Screen/Map` row. Together, the two families give a form for every frame of play and a
screen for every frame of the recording.

### On-screen visibility

`EnemyOnScreen` and friends are **screen-visibility** events: they start when the object
becomes visible and their `duration` runs until it leaves the screen or is defeated. An
object that leaves and returns produces two events. The distinction being drawn is **on
screen**, not **loaded in RAM**: slot occupancy alone means only that the engine is
simulating the object, and games keep objects live well outside the camera. Each game's
predicate and its validation are given in its section below.

Tracks shorter than {tracking.DEFAULT_MIN_FRAMES} frames are dropped as slot churn, and
gaps of up to {tracking.DEFAULT_DEBOUNCE} frames are bridged, because a one-frame flicker
of the slot bookkeeping is not a disappearance the player perceives.

### Controller actions

`Action/*` rows are normalised across games so that the same button role carries the same
label, with the raw button preserved in the **`button`** column. `duration` spans the
hold. `Action/Other` covers buttons with no documented function in the game. Each game's
button mapping is given in its section below.

### Repetition outcomes

Not events, but recorded per repetition in `gamelogs/*_summary.json` under `Outcome`:

| Label | Meaning |
|---|---|
| `cleared` | The level was finished. |
| `failed/killed` | The final death was caused by contact. |
| `failed/fall` | The final death was a fall off the screen. |
| `failed/timeout` | The timer ran out. |
| `incomplete/warp` | The player left through a warp zone. |
| `incomplete/interrupted` | The recording stopped mid-level. |

How each game decides it is given in its section below.

### Validation

Independent checks on the generated events: the schema and controlled vocabulary (V0),
invariants recomputed from the raw RAM by a different route than the generator (V1), and,
for two datasets of the same game, agreement of the enemies met on each level (V2).

What none of that establishes is agreement with what is actually on screen. That needs
the video review in `videogames_utils.events.review`, which samples events, cuts labelled
clips from the frame-aligned recordings, and reports precision and recall per event type.
Until it has been run, the accuracy figures quoted here are about internal consistency,
not about ground truth.

---

## Events per dataset

Rows of each event in each dataset; a dash where the game has no such event.

{_event_matrix(games, counts)}

---

{_game_sections(games)}"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("dataset_dirs", nargs="+")
    ap.add_argument("-o", "--output", required=True)
    args = ap.parse_args(argv)
    games = [load_game(d) for d in args.dataset_dirs]
    counts = {g.task: census(d) for g, d in zip(games, args.dataset_dirs)}
    with open(args.output, "w") as handle:
        handle.write(render(games, counts))
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
